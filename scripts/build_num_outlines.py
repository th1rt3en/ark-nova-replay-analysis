"""Write web/js/numoutline.js: the digits of 'Park Num' (web/fonts/archivo-800-w90.woff2) as SVG paths, each
with a "sticker" outline drawn around it.

Why: a white number with a black outline drawn as SVG text (`stroke` + `paint-order: stroke`) traces every edge of
the glyph, so in the narrow pockets of a "3" (between its arms and the middle bar) the stroke of the two sides meets
and leaves a stray black loop. The outline here is the glyph grown by the outline width, with every hole that
growing closed filled in (a pocket narrower than the outline becomes solid black), while the real counters of
0 4 6 8 9 stay open. That is how a printed sticker outline looks.

Paths are in em units (1 = the font size, y down, baseline at 0), already scaled by the @font-face size-adjust of
'Park Num' (web/css/park-fonts.css), so a path drawn at a font size matches the SVG text it replaces.

Usage: python scripts/build_num_outlines.py   (needs fonttools + skia-pathops: pip install fonttools skia-pathops brotli)
"""
import json
import re
from pathlib import Path

import pathops
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'web' / 'fonts' / 'archivo-800-w90.woff2'
FONTS_CSS = ROOT / 'web' / 'css' / 'park-fonts.css'
OUT = ROOT / 'web' / 'js' / 'numoutline.js'
OUTLINES = {'xnum': 0.06}          # name -> outline width outside the glyph, in em (.12em stroke = .06em outside)


def size_adjust():
    m = re.search(r"font-family: 'Park Num';[^}]*size-adjust: ([\d.]+)%", FONTS_CSS.read_text(encoding='utf8'))
    return float(m.group(1)) / 100


def glyph_path(gs, name):
    p = pathops.Path()
    gs[name].draw(p.getPen(glyphSet=gs))
    p.simplify(fix_winding=True)
    return p


def contours(path):
    for c in path.contours:
        q = pathops.Path()
        c.draw(q.getPen())
        yield q


def fill_holes(path):
    """The path with its holes filled: only the outer contours (fix_winding makes outer contours clockwise)."""
    out = pathops.Path()
    parts = list(contours(path))
    outer = path_outer_dir(parts)
    for q in parts:
        if q.clockwise == outer:
            out = pathops.op(out, q, pathops.PathOp.UNION)
    return out


def path_outer_dir(parts):
    big = max(parts, key=lambda q: abs(q.area))     # the largest contour is an outer one
    return big.clockwise


def sticker(glyph, r):
    grown = pathops.Path()
    glyph.draw(grown.getPen())
    stroke = pathops.Path()
    glyph.draw(stroke.getPen())
    stroke.stroke(2 * r, pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
    stroke.convertConicsToQuads()
    grown = pathops.op(grown, stroke, pathops.PathOp.UNION)
    filled = fill_holes(grown)
    counters = pathops.op(fill_holes(glyph), glyph, pathops.PathOp.DIFFERENCE)       # the glyph's own holes
    keep_open = pathops.op(counters, grown, pathops.PathOp.DIFFERENCE)               # the part of them the outline leaves free
    return pathops.op(filled, keep_open, pathops.PathOp.DIFFERENCE)


class SvgPen(BasePen):
    def __init__(self, scale):
        super().__init__(None)
        self.s, self.d = scale, []

    def _p(self, pt):
        return f'{round(pt[0] * self.s, 4):g} {round(-pt[1] * self.s, 4):g}'

    def _moveTo(self, pt): self.d.append('M' + self._p(pt))
    def _lineTo(self, pt): self.d.append('L' + self._p(pt))
    def _curveToOne(self, a, b, c): self.d.append('C' + ' '.join(self._p(x) for x in (a, b, c)))
    def _qCurveToOne(self, a, b): self.d.append('Q' + ' '.join(self._p(x) for x in (a, b)))
    def _closePath(self): self.d.append('Z')


def svg_d(path, scale):
    pen = SvgPen(scale)
    path.draw(pen)
    return ''.join(pen.d)


def main():
    font = TTFont(FONT)
    upm = font['head'].unitsPerEm
    scale = size_adjust() / upm
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font['hmtx']
    digits = {}
    for ch in '0123456789':
        name = cmap[ord(ch)]
        g = glyph_path(gs, name)
        entry = {'adv': round(hmtx[name][0] * scale, 5), 'glyph': svg_d(g, scale)}
        for key, r_em in OUTLINES.items():
            entry[key] = svg_d(sticker(g, r_em / scale), scale)
        digits[ch] = entry
    body = json.dumps(digits, indent=4)
    OUT.write_text(f"""// GENERATED by scripts/build_num_outlines.py from web/fonts/archivo-800-w90.woff2 ('Park Num'): do not edit.
// The digits as paths (em units, y down, baseline 0, size-adjust applied) with a sticker outline around each: the
// glyph grown by the outline width with the pockets that closes filled in, so a "3" shows no stray loop between its arms.
import {{ svg }} from './util.js';

const DIGITS = {body};

// a white number with a black sticker outline as an SVG <g>, centred on x with its baseline at y (like text-anchor: middle)
export function outlinedNumber(value, x, y, size, style = 'xnum', cls = '') {{
  const chars = String(value).split('').filter((c) => DIGITS[c]);
  const width = chars.reduce((w, c) => w + DIGITS[c].adv, 0);
  const g = svg('g', {{ class: ('outlined-number ' + cls).trim(), stroke: 'none', transform: `translate(${{x}} ${{y}}) scale(${{size}}) translate(${{-width / 2}} 0)`, 'pointer-events': 'none' }});
  let dx = 0;
  const back = [], front = [];
  for (const c of chars) {{
    back.push(svg('path', {{ d: DIGITS[c][style], transform: `translate(${{dx}} 0)`, style: 'fill:#000;stroke:none' }}));
    front.push(svg('path', {{ d: DIGITS[c].glyph, transform: `translate(${{dx}} 0)`, style: 'fill:#fff;stroke:none' }}));
    dx += DIGITS[c].adv;
  }}
  g.append(...back, ...front);                    // every outline first, so a digit's outline never covers its neighbour
  return g;
}}
""", encoding='utf8')
    print('wrote', OUT.relative_to(ROOT), OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
